using System.Text;
using System.Xml.Linq;
using Umbraco.Cms.Core.Models.PublishedContent;
using Umbraco.Extensions;
using UmbracoAI.Web.Seeding.Schema;

namespace UmbracoAI.Web.Seo;

/// <summary>Generates /sitemap.xml (all cultures, hreflang alternates) and /robots.txt from the content tree.</summary>
public static class CrawlerFiles
{
    private const string DefaultChangeFrequency = "weekly";

    private static readonly XNamespace SitemapNs = "http://www.sitemaps.org/schemas/sitemap/0.9";
    private static readonly XNamespace XhtmlNs = "http://www.w3.org/1999/xhtml";

    /// <summary>Crawlers that collect AI training data – blocked when "KI-Trainings-Crawler blockieren" is set.</summary>
    public static readonly IReadOnlyList<string> AiTrainingCrawlers =
        ["GPTBot", "ClaudeBot", "Google-Extended", "Applebot-Extended", "CCBot", "meta-externalagent", "Bytespider"];

    /// <summary>AI search and user-triggered agents – always allowed so the site stays citable in AI answers.</summary>
    public static readonly IReadOnlyList<string> AiSearchAgents =
        ["OAI-SearchBot", "ChatGPT-User", "Claude-SearchBot", "Claude-User", "PerplexityBot", "Perplexity-User"];

    /// <param name="sites">The site in every culture (start page published).</param>
    public static string Sitemap(IReadOnlyList<SiteContext> sites)
    {
        var urls = sites.SelectMany(site => site.Pages()
            .Where(page => !page.IsNoIndex(site.Culture) && !page.Flag(Props.SitemapExclude, site.Culture))
            .Select(page => UrlElement(page, site, sites)));

        var document = new XDocument(
            new XDeclaration("1.0", "utf-8", null),
            new XElement(SitemapNs + "urlset", new XAttribute(XNamespace.Xmlns + "xhtml", XhtmlNs), urls));
        return document.Declaration + "\n" + document.Root;
    }

    public static string Robots(string siteName, bool blockAiTraining, string sitemapUrl, string llmsUrl)
    {
        var builder = new StringBuilder()
            .Append("# robots.txt – ").Append(siteName).Append(" (generated by Umbraco)\n\n")
            .Append("User-agent: *\nAllow: /\nDisallow: /umbraco/\nDisallow: /api/\n\n")
            .Append("# AI search & user agents – allowed so content can be cited in AI answers\n");
        AppendGroup(builder, AiSearchAgents, "Allow: /\nDisallow: /umbraco/");

        builder.Append(blockAiTraining
            ? "# AI training crawlers – blocked (start page › GEO & KI)\n"
            : "# AI training crawlers – allowed (start page › GEO & KI)\n");
        AppendGroup(builder, AiTrainingCrawlers, blockAiTraining ? "Disallow: /" : "Allow: /\nDisallow: /umbraco/");

        return builder
            .Append("Sitemap: ").Append(sitemapUrl).Append('\n')
            .Append("# LLM index (llms.txt): ").Append(llmsUrl).Append('\n')
            .ToString();
    }

    private static void AppendGroup(StringBuilder builder, IEnumerable<string> agents, string rules)
    {
        foreach (string agent in agents)
        {
            builder.Append("User-agent: ").Append(agent).Append('\n');
        }

        builder.Append(rules).Append("\n\n");
    }

    private static XElement UrlElement(IPublishedContent page, SiteContext site, IReadOnlyList<SiteContext> sites)
    {
        var alternates = sites.Where(other => page.IsPublished(other.Culture))
            .Select(other => new XElement(XhtmlNs + "link",
                new XAttribute("rel", "alternate"),
                new XAttribute("hreflang", other.Culture),
                new XAttribute("href", other.PageUrl(page))));

        return new XElement(SitemapNs + "url",
            new XElement(SitemapNs + "loc", site.PageUrl(page)),
            new XElement(SitemapNs + "lastmod", page.UpdateDate.ToString("yyyy-MM-dd")),
            new XElement(SitemapNs + "changefreq", page.Text(Props.SitemapChangeFrequency) ?? DefaultChangeFrequency),
            new XElement(SitemapNs + "priority", page.Text(Props.SitemapPriority) ?? DefaultPriority(page.Level)),
            alternates);
    }

    public static string DefaultPriority(int level) => level switch
    {
        1 => "1.0",
        2 => "0.8",
        _ => "0.6",
    };
}
